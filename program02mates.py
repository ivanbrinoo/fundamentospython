print("Ejemplo de Matematicas")
num1 = 99
num2 = 20

multiplicar = num1 * num2
sumar = num1 + num2
restar = num1 - num2
dividir = num1 / num2
resto = num1 % num2

print(f"{num1} x {num2} = {multiplicar}")
print(f"{num1} + {num2} = {sumar}")
print(f"{num1} - {num2} = {restar}")
print(f"{num1} / {num2} = {dividir}")
print(f"{num1} % {num2} = {resto}")